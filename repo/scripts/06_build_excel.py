def style_header(ws, row, ncol, start=1):
    for c in range(start, start + ncol):
        cell = ws.cell(row, c); cell.fill = HDR; cell.font = HF
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)


def put_df(ws, df, r0=1, c0=1, fmt=None, widths=True, header=True):
    fmt = fmt or {}
    if header:
        for j, c in enumerate(df.columns):
            ws.cell(r0, c0 + j, str(c))
        style_header(ws, r0, len(df.columns), c0)
    off = 1 if header else 0
    for i, row in enumerate(df.itertuples(index=False)):
        for j, v in enumerate(row):
            if isinstance(v, (np.floating, float)) and (math.isnan(v) or math.isinf(v)):
                v = None
            elif isinstance(v, np.generic):
                v = v.item()
            cell = ws.cell(r0 + off + i, c0 + j, v); cell.font = BASE
            f = fmt.get(df.columns[j])
            if f: cell.number_format = f
    if widths:
        for j, c in enumerate(df.columns):
            ws.column_dimensions[L(c0 + j)].width = max(10, min(34, len(str(c)) + 3))


def note(ws, cell, text, fill=None, bold=False, merge_to=None):
    ws[cell] = text; ws[cell].font = BOLD if bold else BASE
    ws[cell].alignment = Alignment(wrap_text=True, vertical="top")
    if fill: ws[cell].fill = fill
    if merge_to: ws.merge_cells(f"{cell}:{merge_to}")


